// The MQTT contract with the ESP32. Limits and shapes must match the firmware exactly.
import { z } from 'zod';

export const LIMITS = {
  washes: 4,
  minSteps: 1,
  maxSteps: 24,
  minMinutes: 1,
  maxMinutes: 99,
  releaseMs: { min: 10, max: 5000 },
  waitS: { min: 1, max: 600 },
  cleanDurMin: { min: 1, max: 30 },
  airSec: { min: 5, max: 120 },
} as const;

export const requestIdSchema = z
  .string()
  .regex(/^[A-Za-z0-9_-]{1,32}$/, 'id must be 1-32 chars of A-Z a-z 0-9 - _');

const liquidStepSchema = z
  .object({
    t: z.enum(['process', 'water', 'uv']),
    m: z.number().int().min(LIMITS.minMinutes).max(LIMITS.maxMinutes),
  })
  .strict();
const breakStepSchema = z.object({ t: z.literal('break') }).strict();

export const stepSchema = z.union([liquidStepSchema, breakStepSchema]);
export const sequenceSchema = z.array(stepSchema).min(LIMITS.minSteps).max(LIMITS.maxSteps);
export const washesSchema = z.tuple([sequenceSchema, sequenceSchema, sequenceSchema, sequenceSchema]);

const releaseMsSchema = z.number().int().min(LIMITS.releaseMs.min).max(LIMITS.releaseMs.max);
const waitSSchema = z.number().int().min(LIMITS.waitS.min).max(LIMITS.waitS.max);
const pulseSchema = z.object({ releaseMs: releaseMsSchema, waitS: waitSSchema }).strict();

export const timingSchema = z
  .object({
    process: pulseSchema,
    water: pulseSchema,
    uv: pulseSchema,
    clean: z
      .object({
        releaseMs: releaseMsSchema,
        waitS: waitSSchema,
        durMin: z.number().int().min(LIMITS.cleanDurMin.min).max(LIMITS.cleanDurMin.max),
      })
      .strict(),
    air: z.object({ sec: z.number().int().min(LIMITS.airSec.min).max(LIMITS.airSec.max) }).strict(),
  })
  .strict();

/** Stored settings, as published by the ESP on config/state. */
export const configSchema = z.object({ washes: washesSchema, timing: timingSchema }).strict();

export type Step = z.infer<typeof stepSchema>;
export type Sequence = z.infer<typeof sequenceSchema>;
export type Timing = z.infer<typeof timingSchema>;
export type Config = z.infer<typeof configSchema>;

// Payloads the backend publishes. The id is generated by the backend.
export const configSetPayloadSchema = z
  .object({ id: requestIdSchema, washes: washesSchema, timing: timingSchema })
  .strict();
export type ConfigSetPayload = z.infer<typeof configSetPayloadSchema>;

export const commandPayloadSchema = z.discriminatedUnion('action', [
  z
    .object({ id: requestIdSchema, action: z.literal('start'), wash: z.number().int().min(1).max(LIMITS.washes) })
    .strict(),
  z.object({ id: requestIdSchema, action: z.literal('pause') }).strict(),
  z.object({ id: requestIdSchema, action: z.literal('resume') }).strict(),
  z.object({ id: requestIdSchema, action: z.literal('stop') }).strict(),
]);
export type CommandPayload = z.infer<typeof commandPayloadSchema>;
export type CommandInput = { action: 'start'; wash: number } | { action: 'pause' | 'resume' | 'stop' };

export const ACK_ERRORS = ['busy', 'invalid', 'storage', 'bad_command', 'not_running', 'not_paused'] as const;
export type AckError = (typeof ACK_ERRORS)[number];

export const ackSchema = z.object({
  id: z.string(),
  ok: z.boolean(),
  error: z.enum(ACK_ERRORS).optional(),
});
export type Ack = z.infer<typeof ackSchema>;

const stepName = z.enum(['process', 'water', 'uv', 'clean', 'air', 'break']);

export const statusSchema = z.object({
  state: z.enum(['idle', 'running', 'paused', 'break', 'done', 'stopped']),
  wash: z.number().int().min(0).max(LIMITS.washes),
  elapsedS: z.number().int().min(0),
  totalS: z.number().int().min(0),
  remainingS: z.number().int(),
  stepIndex: z.number().int().min(0),
  stepNo: z.number().int().min(0),
  stepTotal: z.number().int().min(0),
  step: stepName.nullable(),
  stepRemainingS: z.number().int().min(0),
  pulse: z.number().int().min(0),
  pulseTotal: z.number().int().min(0),
  valve: z.enum(['off', 'release', 'wait', 'air']),
  nextReleaseS: z.number().int().min(0),
  next: stepName.nullable(),
  pauseReason: z.enum(['none', 'operator', 'link']),
});
export type MachineStatus = z.infer<typeof statusSchema>;
export type RunState = MachineStatus['state'];

export const isActiveState = (state: RunState): boolean =>
  state === 'running' || state === 'paused' || state === 'break';
